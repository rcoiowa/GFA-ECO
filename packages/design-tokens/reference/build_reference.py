def lum(h):
 a=[int(h[i:i+2],16)/255 for i in (1,3,5)]; a=[c/12.92 if c<=.04045 else ((c+.055)/1.055)**2.4 for c in a];return sum(c*w for c,w in zip(a,[.2126,.7152,.0722]))
def contrast(a,b):
 x,y=sorted([lum(a),lum(b)]);return (y+.05)/(x+.05)
results=[]
for theme,t in ref['themes'].items():
 for fg,bg,threshold in [('ink','surface',4.5),('muted','surface',4.5),('muted','raised',4.5),('actionText','action',4.5),('accentText','accent',4.5),('onNight','night',4.5),('onNightMuted','night',4.5),('focus','surface',3)]:
  ratio=contrast(t[fg],t[bg]);results.append({'theme':theme,'foreground':fg,'background':bg,'ratio':round(ratio,2),'minimum':threshold,'pass':ratio>=threshold})
assert all(x['pass'] for x in results),results
results.append({'observation':'Original housing amber focus on warm paper','ratio':round(contrast('#d4a017','#fbf8f6'),2),'minimum':3,'pass':False,'correction':'Use plum focus on light; amber may remain in dark mode.'})
(p/'contrast-results.json').write_text(json.dumps(results,indent=2)+'\n')
