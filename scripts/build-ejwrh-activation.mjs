// build-ejwrh-activation.mjs — generates the final 0146 EJWRH document-activation
// migration from the canonical edition files in docs/residences/ejwrh/.
//
// Never hand-transcribe bodies: this script is the only path from the ratified
// markdown to the seeded SQL. Body convention (identical to the ratification
// hash convention): file minus the leading HTML banner comment, trimmed, plus
// exactly one trailing newline. The pinned hashes below the bodies are computed
// here from the same bytes; the migration's own DO block re-verifies them
// against the content_hash the 0139 trigger computes in the database, so a
// drifted file, a bad copy, or a mangled dollar-quote aborts the apply.
//
// Usage: node scripts/build-ejwrh-activation.mjs <effective-date ISO, e.g. 2026-08-31>

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const effectiveDate = process.argv[2];
if (!/^\d{4}-\d{2}-\d{2}$/.test(effectiveDate ?? '')) {
  console.error('usage: node scripts/build-ejwrh-activation.mjs YYYY-MM-DD');
  process.exit(1);
}

const EDITIONS = [
  { key: 'ejwrh_participant_agreement', name: 'EJWRH Participant & Residency Agreement', sig: true, ack: false, file: 'participant-residency-agreement.md' },
  { key: 'ejwrh_resident_handbook', name: 'EJWRH Resident Handbook', sig: false, ack: true, file: 'resident-handbook.md' },
  { key: 'ejwrh_resident_rights_grievance', name: 'EJWRH Resident Rights & Grievance', sig: false, ack: true, file: 'resident-rights-grievance.md' },
  { key: 'ejwrh_screening_policy', name: 'EJWRH Screening Policy', sig: false, ack: true, file: 'screening-policy.md' },
  { key: 'ejwrh_medication_moud_policy', name: 'EJWRH Medication & MOUD Policy', sig: false, ack: true, file: 'medication-moud-policy.md' },
  { key: 'ejwrh_return_to_use_response_policy', name: 'EJWRH Return-to-Use Response Policy', sig: false, ack: true, file: 'return-to-use-response-policy.md' },
];

// The five acknowledgment documents were executive-ratified 2026-08-24 at these
// hashes and are byte-frozen; the build aborts if any drifted. The Agreement's
// hash is recomputed (its counterparty naming and section 5 fee wording changed
// at the 2026-08-31 activation order).
const FROZEN_ACK_HASHES = {
  ejwrh_resident_handbook: '834773861098c23b4a36785952498d157da39d568cdc015ca41667ff627690ba',
  ejwrh_resident_rights_grievance: '285ce0974c803eb8afb134df20ba21175995c320520c9ccc513822fb44167024',
  ejwrh_screening_policy: 'a835849688a9515e5a0adb4d7d43941717fdaefb415748e2b8f98106612cd6c7',
  ejwrh_medication_moud_policy: '6412db49cfe42cbfdfb81beb2d70e2310c42837407820ff90ad1f4dfdd7d605f',
  ejwrh_return_to_use_response_policy: 'c4cbe7669007474cb9e6a4c5178ab4968277ec4cfa28efbb0f050fa07ad86a97',
};

const bodies = {};
const hashes = {};
for (const e of EDITIONS) {
  const raw = readFileSync(join(root, 'docs/residences/ejwrh', e.file), 'utf8');
  const body = raw.replace(/^<!--[\s\S]*?-->\s*/, '').trim() + '\n';
  if (body.includes('$ejwrh_body$')) {
    console.error(`ABORT: ${e.file} contains the dollar-quote tag`);
    process.exit(1);
  }
  bodies[e.key] = body;
  hashes[e.key] = createHash('sha256').update(body, 'utf8').digest('hex');
  if (FROZEN_ACK_HASHES[e.key] && FROZEN_ACK_HASHES[e.key] !== hashes[e.key]) {
    console.error(`ABORT: ${e.key} drifted from its frozen ratified hash (${hashes[e.key]})`);
    process.exit(1);
  }
}

const versionInserts = EDITIONS.map((e) => `insert into recoveryos.document_versions (template_id, version, body_markdown, published_at)
select t.id, '1.0', $ejwrh_body$${bodies[e.key]}$ejwrh_body$, '${effectiveDate}'::timestamptz
from recoveryos.document_templates t
where t.key = '${e.key}'
on conflict (template_id, version) do nothing;`).join('\n\n');

const sql = `-- 0146_ejwrh_document_activation.sql — EJWRH document edition activation.
--
-- Generated by scripts/build-ejwrh-activation.mjs (effective ${effectiveDate}) from the
-- canonical edition files in docs/residences/ejwrh/ — bodies are never hand-transcribed.
--
-- AUTHORITY: five acknowledgment editions executive-ratified 2026-08-24 (frozen hashes);
-- Participant & Residency Agreement executively approved 2026-08-31 with PSA v4.1
-- execution attested by the Executive Director and the counterparty named operatively
-- (Ernest & Johnnie White Recovery House, L.L.C.); e-sign legal review APPROVED WITH
-- ATTACHED REVISIONS 2026-08-24 (e-consent gate + paper parity live via 0145).
-- The record-retention period remains an open records-policy item: no period is asserted
-- in any seeded text; signed artifacts are preserved immutably and indefinitely pending it.
--
-- ON APPLY: EJWRH (residence 2) readiness flips from the single non-overridable
-- 'pending_document_edition' placeholder to the real 1-signature + 5-acknowledgment set;
-- ensure_my_document_assignments starts assigning at residence 2 with no code change.
--
-- ROLLBACK (reversible without deleting evidence):
--   update recoveryos.document_versions dv set published_at = null
--     from recoveryos.document_templates t
--     where t.id = dv.template_id and t.key like 'ejwrh_%'
--       and not exists (select 1 from recoveryos.document_assignments a
--                       where a.document_version_id = dv.id);
--   update recoveryos.document_templates set is_active = false where key like 'ejwrh_%';
--   (Versions already carrying assignments are immutable evidence — never unpublished.)

set search_path = recoveryos, public;

-- 1) Templates: EJWRH-scoped (residence 2), 1 signature + 5 acknowledgments. Idempotent.
insert into recoveryos.document_templates
  (organization_id, key, name, is_active, requires_signature, requires_acknowledgment, residence_id)
select o.id, v.key, v.name, true, v.sig, v.ack, 2
from (values
${EDITIONS.map((e) => `  ('${e.key}', '${e.name.replace(/'/g, "''")}', ${e.sig}, ${e.ack})`).join(',\n')}
) as v(key, name, sig, ack)
cross join (select id from recoveryos.organizations where name = 'Grace For Addictions') o
on conflict (organization_id, key) do update set
  name = excluded.name, is_active = excluded.is_active,
  requires_signature = excluded.requires_signature,
  requires_acknowledgment = excluded.requires_acknowledgment,
  residence_id = excluded.residence_id;

-- 2) Versions: v1.0 published at the executive effective date.
${versionInserts}

-- 3) Hash verification: ABORT unless every seeded version hashes to the pinned
--    expectation (content_hash computed by the 0139 trigger on insert).
do $$
declare v_bad text;
begin
  select string_agg(t.key || '=' || coalesce(dv.content_hash, 'NULL'), ', ') into v_bad
  from recoveryos.document_templates t
  join recoveryos.document_versions dv on dv.template_id = t.id and dv.version = '1.0'
  where t.key like 'ejwrh_%'
    and (t.key, dv.content_hash) not in (
${EDITIONS.map((e) => `      ('${e.key}', '${hashes[e.key]}')`).join(',\n')});
  if v_bad is not null then
    raise exception 'EJWRH ACTIVATION ABORT: seeded text does not match the ratified hashes: %', v_bad;
  end if;
  if (select count(*) from recoveryos.document_templates t
      join recoveryos.document_versions dv on dv.template_id = t.id
        and dv.version = '1.0' and dv.published_at is not null
      where t.key like 'ejwrh_%') <> 6 then
    raise exception 'EJWRH ACTIVATION ABORT: expected exactly 6 published v1.0 editions';
  end if;
end $$;

notify pgrst, 'reload schema';
`;

const out = join(root, 'supabase/launch/migrations/0146_ejwrh_document_activation.sql');
writeFileSync(out, sql);
console.log('wrote', out);
for (const e of EDITIONS) console.log(`${e.key}  ${hashes[e.key]}`);
